import {test,expect} from "@playwright/test";
const PASSWORD="Another-Strong-Device-Password-2026";
test("offline debts and receipts mirror cash exactly once across reload",async({page})=>{
  const external:string[]=[];
  page.on("request",req=>{if(!req.url().startsWith("http://127.0.0.1:4179/"))external.push(req.url());});
  await page.goto("/");
  await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill(PASSWORD);
  await page.getByLabel("تأكيد كلمة السر").fill(PASSWORD);
  await page.getByRole("button",{name:"إنشاء خزنة محلية"}).click();
  await expect(page.getByRole("heading",{name:"المحافظ والأرصدة"})).toBeVisible();
  await page.getByLabel("اسم المحفظة").fill("خزنة المنزل");
  await page.getByLabel("الرصيد الافتتاحي (ريال)").fill("500");
  await page.getByRole("button",{name:"إضافة محفظة"}).click();
  await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","50000");
  await page.getByLabel("اسم الشخص").fill("شخص الاختبار");
  await page.getByLabel("مبلغ الدين (ريال)").fill("200");
  await page.getByLabel("المحفظة التي تحرك فيها أصل المبلغ").selectOption({label:"خزنة المنزل"});
  await page.getByRole("button",{name:"حفظ الدين"}).click();
  await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","30000");
  await expect(page.getByTestId("total-receivable")).toHaveAttribute("data-halalas","20000");
  await page.getByLabel("قيمة التحصيل (ريال)").fill("50");
  await page.getByLabel("المحفظة التي تحرك فيها المبلغ").selectOption({label:"خزنة المنزل"});
  await page.getByRole("button",{name:"تسجيل التحصيل"}).click();
  await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","35000");
  await expect(page.getByTestId("total-receivable")).toHaveAttribute("data-halalas","15000");
  await page.reload();
  await expect(page.getByRole("heading",{name:"افتح خزنتك"})).toBeVisible();
  await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill(PASSWORD);
  await page.getByRole("button",{name:"فتح الخزنة"}).click();
  await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","35000");
  await expect(page.getByTestId("total-receivable")).toHaveAttribute("data-halalas","15000");
  expect(external).toEqual([]);
});
