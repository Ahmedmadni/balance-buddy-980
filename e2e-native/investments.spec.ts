import {test,expect} from "@playwright/test";
const PASSWORD="Investment-Vault-Password-2026";
test("offline gold buy, partial sale, market valuation and reboot",async({page})=>{
 const thirdParty:string[]=[];
 page.on("request",r=>{if(!r.url().startsWith("http://127.0.0.1:4179/"))thirdParty.push(r.url());});
 await page.goto("/");
 await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill(PASSWORD);
 await page.getByLabel("تأكيد كلمة السر").fill(PASSWORD);
 await page.getByRole("button",{name:"إنشاء خزنة محلية"}).click();
 await page.getByLabel("اسم المحفظة").fill("خزنة الذهب");
 await page.getByLabel("الرصيد الافتتاحي (ريال)").fill("1000");
 await page.getByRole("button",{name:"إضافة محفظة"}).click();
 await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","100000");
 await page.getByLabel("اسم الاستثمار").fill("ذهب 24 قيراط");
 await page.getByLabel("سعر السوق الحالي بالريال للوحدة (اختياري)").fill("350");
 await page.getByRole("button",{name:"إضافة الاستثمار"}).click();
 const asset=page.getByTestId("investment-position");
 await expect(asset).toHaveCount(1);
 await page.getByLabel("الكمية بالجرام أو الوحدة (حتى 3 منازل)").fill("2");
 await page.getByLabel("سعر الشراء أو البيع للوحدة بالريال").fill("300");
 await page.getByLabel("المحفظة المرتبطة بالحركة").selectOption({label:"خزنة الذهب"});
 await page.getByRole("button",{name:"تسجيل الشراء"}).click();
 await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","40000");
 await expect(asset.getByTestId("investment-cost")).toHaveAttribute("data-halalas","60000");
 await expect(asset.getByTestId("investment-market")).toHaveAttribute("data-halalas","70000");
 await page.getByLabel("نوع الحركة").selectOption("sell");
 await page.getByLabel("الكمية بالجرام أو الوحدة (حتى 3 منازل)").fill("0.5");
 await page.getByLabel("سعر الشراء أو البيع للوحدة بالريال").fill("400");
 await page.getByRole("button",{name:"تسجيل البيع"}).click();
 await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","60000");
 await expect(asset.getByTestId("investment-cost")).toHaveAttribute("data-halalas","45000");
 await expect(asset.getByTestId("investment-realized")).toHaveAttribute("data-halalas","5000");
 await page.reload();
 await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill(PASSWORD);
 await page.getByRole("button",{name:"فتح الخزنة"}).click();
 await expect(page.getByTestId("wallet-balance")).toHaveAttribute("data-halalas","60000");
 await expect(page.getByTestId("investment-realized")).toHaveAttribute("data-halalas","5000");
 expect(thirdParty).toEqual([]);
});
