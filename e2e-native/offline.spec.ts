import {test,expect} from "@playwright/test";
const PASSWORD="A-Strong-Offline-Vault-Password-2026";
test("Android vault stores wallets and money without cloud login or network",async({page})=>{
  const thirdParty:string[]=[];
  page.on("request",req=>{if(!req.url().startsWith("http://127.0.0.1:4179/"))thirdParty.push(req.url());});
  await page.goto("/");
  await expect(page.getByRole("heading",{name:"ابدأ بدون حساب"})).toBeVisible();
  await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill(PASSWORD);
  await page.getByLabel("تأكيد كلمة السر").fill(PASSWORD);
  await page.getByRole("button",{name:"إنشاء خزنة محلية"}).click();
  await expect(page.getByRole("heading",{name:"المحافظ والأرصدة"})).toBeVisible();
  await page.getByPlaceholder("نقدي، حساب بنكي...").fill("محفظة الاختبار");
  await page.getByLabel("الرصيد الافتتاحي (ريال)").fill("150.50");
  await page.getByRole("button",{name:"إضافة محفظة"}).click();
  await expect(page.getByText("محفظة الاختبار").first()).toBeVisible();
  await page.getByLabel("المبلغ بالريال").fill("20.25");
  await page.getByLabel("التصنيف").fill("الطعام");
  await page.getByRole("button",{name:"حفظ العملية"}).click();
  await expect(page.getByText("الطعام")).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading",{name:"افتح خزنتك"})).toBeVisible();
  await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill("wrongpassword123");
  await page.getByRole("button",{name:"فتح الخزنة"}).click();
  await expect(page.getByRole("alert")).toContainText("كلمة السر غير صحيحة");
  await page.getByLabel("كلمة سر الخزنة (12 حرفًا على الأقل)").fill(PASSWORD);
  await page.getByRole("button",{name:"فتح الخزنة"}).click();
  await expect(page.getByText("محفظة الاختبار").first()).toBeVisible();
  await expect(page.getByText("الطعام")).toBeVisible();
  expect(thirdParty).toEqual([]);
});
